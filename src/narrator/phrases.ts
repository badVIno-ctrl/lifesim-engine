/** Достаток словами, без единой цифры: сравнением с ценами этого мира. */
export function wealthWord(money: number, dayFood: number): string {
	if (dayFood <= 0) return "деньги есть, и счёт им ты знаешь сам"
	const days = money / dayFood
	if (days < 1) return "в кармане пусто настолько, что и на еду не наберётся"
	if (days < 3) return "в кармане на пару дней еды, не больше"
	if (days < 10) return "деньги есть, но каждый расход придётся выбирать"
	if (days < 40) return "запас есть, и он даёт время думать"
	return "денег больше, чем ты привык носить с собой"
}
