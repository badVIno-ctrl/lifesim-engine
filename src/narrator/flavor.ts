// «Вкус» мира: чем пахнет, что звучит, куда можно пойти и чем можно заработать.
// Изоморфно: ни fs, ни path, ни process.
//
// Своему движку нельзя знать заранее, в каком мире он оказался: игрок задаёт
// сеттинг строкой. Поэтому вкус определяется по словам этой строки, а не по
// списку разрешённых миров, и всегда есть общий слой, который годится для любого места.
// Заработки и цены заданы не числами, а множителями к якорю «еда на день» из пака,
// поэтому один и тот же движок работает и в грошах, и в кронах.

export type FlavorId = "город" | "порт" | "село" | "промысел" | "дорога" | "общий"

export type WorkOffer = {
	what: string
	/** Плата в «днях еды»: числа берутся из economy.anchors, а не из воздуха. */
	pay: [number, number]
	/** Сколько это занимает по времени, в минутах. */
	minutes: [number, number]
	tags: string[]
}

export type Flavor = {
	id: FlavorId
	/** Корни слов, по которым мир узнаётся в описании сеттинга. */
	match: string[]
	/** Куда осмысленно пойти. Именительный падеж: движок вставляет их в безопасные рамки. */
	places: string[]
	/** Обстановка: то, что можно заметить, тронуть, сломать. */
	props: string[]
	/** Случайные лица: не NPC с агендой, а фон, который делает мир обжитым. */
	people: string[]
	work: WorkOffer[]
	sights: string[]
	sounds: string[]
	smells: string[]
	touches: string[]
	tastes: string[]
	/** Открытые вопросы, которыми движок пополняет реестр неустановленного. */
	questions: string[]
}

